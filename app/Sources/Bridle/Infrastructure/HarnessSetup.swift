import Foundation

/// Generated, Bridle-owned wiring for one harness: a launch `.command` file
/// (plus a README) under Application Support. Selecting a harness writes
/// these files; the harness's own global configuration is never edited —
/// anything stateful (provider registration) happens only when the user
/// runs the launch file, through that harness's supported CLI.
struct HarnessWiring: Equatable {
    let harness: Harness
    let model: String
    let endpoint: String
    let directory: URL
    let launchFile: URL
    let launchCommand: String
}

enum HarnessSetup {
    static func detect(_ harness: Harness) -> String? {
        harness.binaryCandidates.first { FileManager.default.isExecutableFile(atPath: $0) }
    }

    static func baseDirectory() -> URL {
        EngineLocator.supportDirectory.appendingPathComponent("harness", isDirectory: true)
    }

    /// Escapes a value for interpolation inside shell double quotes.
    static func dq(_ value: String) -> String {
        value.replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
            .replacingOccurrences(of: "$", with: "\\$")
            .replacingOccurrences(of: "`", with: "\\`")
    }

    // ---- file contents (pure, unit-tested) -------------------------------------------------

    static func claudeScript(endpoint: String, token: String, model: String, binary: String,
                              contextTokens: Int? = nil) -> String {
        let contextLine = contextTokens.map {
            "export CLAUDE_CODE_MAX_CONTEXT_TOKENS=\"\($0)\"  # the loaded model's real window (Claude assumes 200k otherwise)"
        } ?? "# (model context length unknown; Claude Code assumes 200k)"
        return """
        #!/bin/zsh
        # Generated by Bridle — launches Claude Code against the model Bridle is serving.
        # Regenerated whenever the harness, model, or port changes. Your ~/.claude config is untouched.
        export ANTHROPIC_BASE_URL="\(dq(endpoint))"
        export ANTHROPIC_AUTH_TOKEN="\(dq(token))"
        export ANTHROPIC_MODEL="\(dq(model))"
        export ANTHROPIC_SMALL_FAST_MODEL="\(dq(model))"
        \(contextLine)
        echo "Claude Code via Bridle: \(dq(model)) at \(dq(endpoint))"
        exec "\(dq(binary))" "$@"
        """
    }

    static func deepseekScript(endpoint: String, token: String, model: String, dshctl: String,
                                contextTokens: Int? = nil) -> String {
        let context = contextTokens ?? 65536
        return """
        #!/bin/zsh
        # Generated by Bridle — registers Bridle as a provider in DeepSeek Harness and
        # shows it ready to pick. Uses dshctl's supported add-model; your other
        # providers and sessions are untouched. Re-run after switching models.
        set -e
        # dshctl status exits 0 even when the host is down, so probe the port directly.
        if ! curl -s -m 2 -o /dev/null "${DSH_URL:-http://127.0.0.1:3080}"; then
          echo "DeepSeek Harness (dsh web) is not running."
          echo "Start it with:  dsh web"
          echo "then run this file again."
          exit 1
        fi
        DSH_MODEL_API_KEY="\(dq(token))" "\(dq(dshctl))" add-model --id bridle \\
          --base-url "\(dq(endpoint))/v1" --model "\(dq(model))" \\
          --display-name "Bridle (this Mac)" --name "\(dq(model)) via Bridle" \\
          --context \(context) --max-tokens 8192 --force
        echo
        echo "Bridle is registered in DeepSeek Harness as provider 'bridle'."
        echo "In a dsh session pick 'Bridle (this Mac)', or: dshctl use-model <session-id> bridle \(dq(model))"
        "\(dq(dshctl))" models || true
        """
    }

    static func codexScript(endpoint: String, token: String, model: String, binary: String) -> String {
        // Codex takes config overrides on the command line (-c key=value), so the
        // user's ~/.codex/config.toml never needs editing.
        """
        #!/bin/zsh
        # Generated by Bridle — launches Codex against Bridle's Responses API.
        # Regenerated whenever the harness, model, or port changes. ~/.codex/config.toml is untouched.
        export BRIDLE_API_KEY="\(dq(token))"
        echo "Codex via Bridle: \(dq(model)) at \(dq(endpoint))"
        exec "\(dq(binary))" -c 'model_provider="bridle"' -c 'model="\(dq(model))"' \\
          -c 'model_providers.bridle={ name = "Bridle (this Mac)", base_url = "\(dq(endpoint))/v1", env_key = "BRIDLE_API_KEY", wire_api = "responses" }' \\
          "$@"
        """
    }

    static func opencodeConfig(endpoint: String, token: String, model: String) -> String {
        // Written next to the launch file and passed via OPENCODE_CONFIG.
        let escapedModel = model.replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
        let escapedEndpoint = endpoint.replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
        let escapedToken = token.replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
        return """
        {
          "$schema": "https://opencode.ai/config.json",
          "model": "bridle/\(escapedModel)",
          "provider": {
            "bridle": {
              "npm": "@ai-sdk/openai-compatible",
              "name": "Bridle (this Mac)",
              "options": {
                "baseURL": "\(escapedEndpoint)/v1",
                "apiKey": "\(escapedToken)"
              },
              "models": {
                "\(escapedModel)": { "name": "\(escapedModel) via Bridle" }
              }
            }
          }
        }
        """
    }

    static func opencodeScript(configPath: String, binary: String) -> String {
        """
        #!/bin/zsh
        # Generated by Bridle — launches OpenCode with a Bridle provider config.
        # Regenerated whenever the harness, model, or port changes. Your global
        # ~/.config/opencode config is untouched (OPENCODE_CONFIG points here).
        export OPENCODE_CONFIG="\(dq(configPath))"
        exec "\(dq(binary))" "$@"
        """
    }

    static func lemonadeScript(endpoint: String, token: String, binary: String) -> String {
        """
        #!/bin/zsh
        # Generated by Bridle — registers Bridle as an OpenAI-compatible provider in
        # your Lemonade server. Undo any time with:  lemonade cloud uninstall bridle
        set -e
        if ! "\(dq(binary))" status >/dev/null 2>&1; then
          echo "Lemonade server is not running. Open the Lemonade app (or run its server),"
          echo "then run this file again."
          exit 1
        fi
        "\(dq(binary))" cloud uninstall bridle >/dev/null 2>&1 || true
        "\(dq(binary))" cloud install bridle --base-url "\(dq(endpoint))/v1" --allow-insecure-http
        # Hand the running server the key for this provider (in-memory runtime key).
        "\(dq(binary))" cloud auth bridle --api-key "\(dq(token))" --allow-insecure-http || true
        echo
        echo "Bridle is registered in Lemonade as provider 'bridle' (\(dq(endpoint))/v1)."
        "\(dq(binary))" cloud list || true
        """
    }

    static func readme(harness: Harness, endpoint: String, model: String) -> String {
        """
        # \(harness.displayName) via Bridle

        Generated by Bridle. \(harness.wiringSummary)

        - Endpoint: \(endpoint)
        - Model: \(model)
        - Launch: open the .command file in this folder (or use Launch in Bridle's Harness menu).

        Bridle regenerates these files when the harness, model, or port changes.
        Nothing here edits \(harness.displayName)'s own global configuration files.
        """
    }

    static func launchCommand(harness: Harness, launchFile: URL) -> String {
        "open \"\(launchFile.path)\""
    }

    // ---- writing ----------------------------------------------------------------------------

    static func writeWiring(harness: Harness, port: Int, model: String, token: String,
                            contextTokens: Int? = nil,
                            baseDirectory: URL = HarnessSetup.baseDirectory()) throws -> HarnessWiring {
        let endpoint = "http://127.0.0.1:\(port)"
        let dir = baseDirectory.appendingPathComponent(harness.rawValue, isDirectory: true)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        // Launch files embed the API token: owner-only, like the Keychain item they mirror.
        try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: dir.path)
        let binary = detect(harness) ?? harness.binaryCandidates.first!
        let script: String
        let fileName: String
        switch harness {
        case .deepseek:
            script = deepseekScript(endpoint: endpoint, token: token, model: model, dshctl: binary,
                                    contextTokens: contextTokens)
            fileName = "Wire DeepSeek Harness.command"
        case .claudeCode:
            script = claudeScript(endpoint: endpoint, token: token, model: model, binary: binary,
                                  contextTokens: contextTokens)
            fileName = "Launch Claude Code.command"
        case .codex:
            script = codexScript(endpoint: endpoint, token: token, model: model, binary: binary)
            fileName = "Launch Codex.command"
        case .opencode:
            let config = dir.appendingPathComponent("opencode.json")
            try (opencodeConfig(endpoint: endpoint, token: token, model: model) + "\n")
                .write(to: config, atomically: true, encoding: .utf8)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: config.path)
            script = opencodeScript(configPath: config.path, binary: binary)
            fileName = "Launch OpenCode.command"
        case .lemonade:
            script = lemonadeScript(endpoint: endpoint, token: token, binary: binary)
            fileName = "Wire Lemonade.command"
        }
        let launch = dir.appendingPathComponent(fileName)
        try (script + "\n").write(to: launch, atomically: true, encoding: .utf8)
        try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: launch.path)
        let readmeFile = dir.appendingPathComponent("README.md")
        try readme(harness: harness, endpoint: endpoint, model: model)
            .write(to: readmeFile, atomically: true, encoding: .utf8)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: readmeFile.path)
        return HarnessWiring(harness: harness, model: model, endpoint: endpoint, directory: dir,
                             launchFile: launch,
                             launchCommand: launchCommand(harness: harness, launchFile: launch))
    }
}
